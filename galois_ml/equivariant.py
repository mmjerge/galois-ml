"""Galois-equivariant neural network layers.

Gal(GF(p^n)/F_p) is cyclic of order n, generated by Frobenius. In a
normal basis (see `galois_ml.finite_field.NormalBasis`) Frobenius acts on
coordinate vectors by a cyclic shift, i.e. the regular representation of
C_n. A linear map commuting with all cyclic shifts is exactly a circulant
matrix - a group convolution over C_n. Stacking such maps (per channel)
with pointwise nonlinearities gives Frobenius-equivariant networks, and
averaging over the orbit dimension gives Frobenius-invariant readouts.

This mirrors how translation equivariance yields CNNs: here the symmetry
group is arithmetic (the Galois group) rather than spatial. Functions
worth learning on finite fields - norm, trace, being a k-th power,
membership in a subfield - are all Galois-invariant, so the architecture
matches the label structure by construction.
"""

from __future__ import annotations

import torch
import torch.nn as nn


class CyclicEquivariantLinear(nn.Module):
    """Linear layer (B, C_in, n) -> (B, C_out, n) commuting with cyclic
    shifts of the last dimension: a multi-channel circulant map / group
    convolution over C_n.

    y[b, o, i] = sum_{c, j} w[o, c, (j - i) mod n] * x[b, c, j] + bias[o]

    Bias is per-channel (constant along the orbit dimension), which
    preserves equivariance.
    """

    def __init__(self, in_channels: int, out_channels: int, n: int, bias: bool = True):
        super().__init__()
        self.n = n
        scale = (in_channels * n) ** -0.5
        self.weight = nn.Parameter(
            torch.randn(out_channels, in_channels, n) * scale
        )
        self.bias = nn.Parameter(torch.zeros(out_channels)) if bias else None
        idx = torch.arange(n)
        # index[i, j] = (j - i) mod n
        self.register_buffer("index", (idx.unsqueeze(0) - idx.unsqueeze(1)) % n)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        # circulant[o, c, i, j] = weight[o, c, (j - i) mod n]
        circulant = self.weight[:, :, self.index]
        y = torch.einsum("bcj,ocij->boi", x, circulant)
        if self.bias is not None:
            y = y + self.bias.unsqueeze(-1)
        return y


class FrobeniusInvariantPool(nn.Module):
    """Average over the orbit (Galois) dimension: (B, C, n) -> (B, C).

    Composed after equivariant layers, this makes the whole network
    exactly invariant under the Frobenius action.
    """

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return x.mean(dim=-1)


class GaloisInvariantNet(nn.Module):
    """Frobenius-invariant classifier on GF(p^n) in normal coordinates.

    Input: integer tensors of shape (B, n) with entries in {0, ..., p-1}
    (normal coordinates of field elements). Coordinates are one-hot
    encoded into p channels - a shift-equivariant, field-respecting
    embedding - then passed through cyclic-equivariant layers, an
    invariant pool, and a linear head.

    The network satisfies f(Frobenius(x)) = f(x) *exactly*, for any
    weights: the Galois symmetry is architectural, not learned.
    """

    def __init__(
        self,
        p: int,
        n: int,
        n_classes: int = 2,
        hidden_channels: int = 32,
        depth: int = 3,
    ):
        super().__init__()
        self.p, self.n = p, n
        layers: list[nn.Module] = []
        c_in = p
        for _ in range(depth):
            layers.append(CyclicEquivariantLinear(c_in, hidden_channels, n))
            layers.append(nn.ReLU())
            c_in = hidden_channels
        self.equivariant = nn.Sequential(*layers)
        self.pool = FrobeniusInvariantPool()
        self.head = nn.Linear(hidden_channels, n_classes)

    def forward(self, coords: torch.Tensor) -> torch.Tensor:
        # (B, n) ints -> one-hot (B, p, n)
        x = torch.nn.functional.one_hot(coords.long(), self.p)
        x = x.permute(0, 2, 1).float()
        x = self.equivariant(x)
        return self.head(self.pool(x))


class PlainMLP(nn.Module):
    """Non-equivariant baseline with the same one-hot input encoding,
    for measuring the inductive-bias advantage of Galois equivariance."""

    def __init__(
        self,
        p: int,
        n: int,
        n_classes: int = 2,
        hidden: int = 128,
        depth: int = 3,
    ):
        super().__init__()
        self.p, self.n = p, n
        dims = [p * n] + [hidden] * depth
        layers: list[nn.Module] = []
        for d_in, d_out in zip(dims[:-1], dims[1:]):
            layers += [nn.Linear(d_in, d_out), nn.ReLU()]
        layers.append(nn.Linear(hidden, n_classes))
        self.net = nn.Sequential(*layers)

    def forward(self, coords: torch.Tensor) -> torch.Tensor:
        x = torch.nn.functional.one_hot(coords.long(), self.p)
        return self.net(x.float().flatten(1))


class GroupEquivariantLinear(nn.Module):
    """Linear layer (B, C_in, |G|) -> (B, C_out, |G|) commuting with the
    left-regular representation of an arbitrary finite group G: group
    convolution W[h, k] = w[h^{-1} k]. For G = C_n this reduces to
    `CyclicEquivariantLinear` (circulant matrices).

    This is the architecture for Galois groups that are not cyclic
    (e.g. Gal(K/Q) = S3, D4, Q8 for number fields K/Q): a totally real
    Galois K embeds into R^{|G|} by its archimedean embeddings, on which
    G acts by the regular representation.
    """

    def __init__(self, group, in_channels: int, out_channels: int, bias: bool = True):
        super().__init__()
        from galois_ml.group_algebra import FiniteGroup

        if not isinstance(group, FiniteGroup):
            raise TypeError("group must be a FiniteGroup")
        self.group = group
        n = group.order
        scale = (in_channels * n) ** -0.5
        self.weight = nn.Parameter(
            torch.randn(out_channels, in_channels, n) * scale
        )
        self.bias = nn.Parameter(torch.zeros(out_channels)) if bias else None
        self.register_buffer(
            "index", torch.from_numpy(group.convolution_index()).long()
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        # conv_matrix[o, c, h, k] = weight[o, c, h^{-1} k]
        conv_matrix = self.weight[:, :, self.index]
        y = torch.einsum("bck,ochk->boh", x, conv_matrix)
        if self.bias is not None:
            y = y + self.bias.unsqueeze(-1)
        return y


class GroupInvariantNet(nn.Module):
    """G-invariant network on features indexed by a finite group G:
    stacked group convolutions, orbit-average pooling, linear head.
    Satisfies f(L_g x) = f(x) exactly for all g in G and any weights.
    """

    def __init__(
        self,
        group,
        n_classes: int = 2,
        in_channels: int = 1,
        hidden_channels: int = 32,
        depth: int = 3,
    ):
        super().__init__()
        self.group = group
        layers: list[nn.Module] = []
        c_in = in_channels
        for _ in range(depth):
            layers.append(GroupEquivariantLinear(group, c_in, hidden_channels))
            layers.append(nn.ReLU())
            c_in = hidden_channels
        self.equivariant = nn.Sequential(*layers)
        self.pool = FrobeniusInvariantPool()
        self.head = nn.Linear(hidden_channels, n_classes)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        if x.dim() == 2:  # (B, |G|) -> single channel
            x = x.unsqueeze(1)
        x = self.equivariant(x.float())
        return self.head(self.pool(x))
