"""Exact arithmetic in GF(p^n) with normal bases.

This is the substrate for "representations that live over finite fields":
elements of GF(p^n) are coefficient vectors over F_p, and Gal(GF(p^n)/F_p)
is cyclic of order n, generated by the Frobenius x -> x^p.

A *normal basis* is a basis of the form {theta, theta^p, ..., theta^{p^{n-1}}}
(the Frobenius orbit of a single element). In normal coordinates the
Frobenius acts by a cyclic shift of coordinates, so the Galois action
becomes the regular representation of C_n. That is what lets us build
Galois-equivariant networks with ordinary cyclic group convolutions
(see `galois_ml.equivariant`).
"""

from __future__ import annotations

import numpy as np


def _inverse_mod_matrix(M: np.ndarray, p: int) -> np.ndarray:
    """Inverse of a square matrix over F_p via Gauss-Jordan elimination."""
    n = M.shape[0]
    A = np.concatenate([M % p, np.eye(n, dtype=np.int64)], axis=1)
    row = 0
    for col in range(n):
        pivot = next((r for r in range(row, n) if A[r, col] % p != 0), None)
        if pivot is None:
            raise ValueError("matrix is singular mod p")
        A[[row, pivot]] = A[[pivot, row]]
        A[row] = (A[row] * pow(int(A[row, col]), p - 2, p)) % p
        for r in range(n):
            if r != row and A[r, col] % p != 0:
                A[r] = (A[r] - A[r, col] * A[row]) % p
        row += 1
    return A[:, n:]


def _rank_mod(M: np.ndarray, p: int) -> int:
    """Rank of a matrix over F_p."""
    A = (M % p).astype(np.int64).copy()
    n_rows, n_cols = A.shape
    rank = 0
    for col in range(n_cols):
        pivot = next(
            (r for r in range(rank, n_rows) if A[r, col] % p != 0), None
        )
        if pivot is None:
            continue
        A[[rank, pivot]] = A[[pivot, rank]]
        A[rank] = (A[rank] * pow(int(A[rank, col]), p - 2, p)) % p
        for r in range(n_rows):
            if r != rank and A[r, col] % p != 0:
                A[r] = (A[r] - A[r, col] * A[rank]) % p
        rank += 1
    return rank


class GF:
    """The finite field GF(p^n), n >= 2.

    Elements are numpy int64 vectors of length n: coefficients (ascending
    degree) of polynomials in F_p[x] modulo a monic irreducible of degree n.
    """

    def __init__(self, p: int, n: int, seed: int = 0):
        if n < 2:
            raise ValueError("use n >= 2 (GF(p) needs no extension)")
        self.p, self.n, self.q = p, n, p**n
        self.modulus = self._find_irreducible(np.random.default_rng(seed))

    def _find_irreducible(self, rng: np.random.Generator) -> np.ndarray:
        from sympy import Poly, symbols

        x = symbols("x")
        while True:
            low = rng.integers(0, self.p, size=self.n)
            coeffs_desc = [1] + [int(c) for c in low[::-1]]  # monic
            if Poly(coeffs_desc, x, modulus=self.p).is_irreducible:
                # store ascending: modulus[i] is the coefficient of x^i
                return np.array(coeffs_desc[::-1], dtype=np.int64)

    # -- element construction ------------------------------------------

    def zero(self) -> np.ndarray:
        return np.zeros(self.n, dtype=np.int64)

    def one(self) -> np.ndarray:
        e = self.zero()
        e[0] = 1
        return e

    def from_int(self, k: int) -> np.ndarray:
        """Element with base-p digits of k as coefficients (a bijection
        {0..q-1} -> GF(p^n) as sets, not a ring homomorphism)."""
        digits = []
        for _ in range(self.n):
            digits.append(k % self.p)
            k //= self.p
        return np.array(digits, dtype=np.int64)

    def random_element(self, rng: np.random.Generator) -> np.ndarray:
        return rng.integers(0, self.p, size=self.n).astype(np.int64)

    def all_elements(self):
        """Iterate over all q elements (small fields only)."""
        for k in range(self.q):
            yield self.from_int(k)

    # -- arithmetic ------------------------------------------------------

    def add(self, a: np.ndarray, b: np.ndarray) -> np.ndarray:
        return (a + b) % self.p

    def sub(self, a: np.ndarray, b: np.ndarray) -> np.ndarray:
        return (a - b) % self.p

    def _reduce(self, c: np.ndarray) -> np.ndarray:
        """Reduce a polynomial (ascending coeffs) modulo the field modulus."""
        c = c % self.p
        for d in range(len(c) - 1, self.n - 1, -1):
            if c[d]:
                # x^n = -(modulus[0..n-1]), since the modulus is monic
                c[d - self.n : d] = (
                    c[d - self.n : d] - c[d] * self.modulus[: self.n]
                ) % self.p
                c[d] = 0
        return c[: self.n]

    def mul(self, a: np.ndarray, b: np.ndarray) -> np.ndarray:
        return self._reduce(np.convolve(a, b))

    def pow(self, a: np.ndarray, k: int) -> np.ndarray:
        if k < 0:
            return self.pow(self.inverse(a), -k)
        result, base = self.one(), a.copy()
        while k:
            if k & 1:
                result = self.mul(result, base)
            base = self.mul(base, base)
            k >>= 1
        return result

    def inverse(self, a: np.ndarray) -> np.ndarray:
        if not a.any():
            raise ZeroDivisionError("zero has no inverse")
        return self.pow(a, self.q - 2)

    # -- Galois action ----------------------------------------------------

    def frobenius(self, a: np.ndarray, power: int = 1) -> np.ndarray:
        """sigma^power(a) where sigma(x) = x^p generates Gal(GF(p^n)/F_p)."""
        return self.pow(a, self.p ** (power % self.n))

    def trace(self, a: np.ndarray) -> int:
        """Tr(a) = a + a^p + ... + a^{p^{n-1}} in F_p."""
        acc, x = self.zero(), a.copy()
        for _ in range(self.n):
            acc = self.add(acc, x)
            x = self.frobenius(x)
        assert not acc[1:].any(), "trace must land in F_p"
        return int(acc[0])

    def norm(self, a: np.ndarray) -> int:
        """N(a) = a^{(q-1)/(p-1)} in F_p."""
        if not a.any():
            return 0
        result = self.pow(a, (self.q - 1) // (self.p - 1))
        assert not result[1:].any(), "norm must land in F_p"
        return int(result[0])

    def is_square(self, a: np.ndarray) -> bool:
        """Whether a is a square in GF(p^n) (zero counts as a square)."""
        if not a.any():
            return True
        if self.p == 2:
            return True  # squaring is a bijection in characteristic 2
        e = self.pow(a, (self.q - 1) // 2)
        return bool(np.array_equal(e, self.one()))

    # -- normal basis -----------------------------------------------------

    def find_normal_element(
        self, rng: np.random.Generator | None = None, max_tries: int = 1000
    ) -> np.ndarray:
        """Find theta whose Frobenius orbit {theta^{p^i}} is a basis.

        Normal elements always exist (normal basis theorem) and are
        plentiful, so random search terminates quickly.
        """
        rng = rng or np.random.default_rng(0)
        for _ in range(max_tries):
            theta = self.random_element(rng)
            orbit = self._frobenius_orbit(theta)
            if _rank_mod(orbit, self.p) == self.n:
                return theta
        raise RuntimeError("no normal element found (should not happen)")

    def _frobenius_orbit(self, theta: np.ndarray) -> np.ndarray:
        """Matrix whose i-th row is sigma^i(theta) in standard coords."""
        rows, x = [], theta.copy()
        for _ in range(self.n):
            rows.append(x)
            x = self.frobenius(x)
        return np.stack(rows)

    def normal_basis(self, seed: int = 0) -> "NormalBasis":
        theta = self.find_normal_element(np.random.default_rng(seed))
        return NormalBasis(self, theta)


class NormalBasis:
    """Coordinates on GF(p^n) in which Frobenius is a cyclic shift.

    If x = sum_i c_i sigma^i(theta), then sigma(x) = sum_i c_i
    sigma^{i+1}(theta), i.e. normal coordinates transform by
    c -> roll(c, 1). This turns Gal(GF(p^n)/F_p) into the regular
    representation of C_n acting on coordinate vectors.
    """

    def __init__(self, field: GF, theta: np.ndarray):
        self.field = field
        self.theta = theta
        self.basis_matrix = field._frobenius_orbit(theta)  # rows: sigma^i(theta)
        self.inverse_matrix = _inverse_mod_matrix(self.basis_matrix, field.p)

    def to_normal(self, x: np.ndarray) -> np.ndarray:
        """Standard (polynomial) coords -> normal coords."""
        return (x @ self.inverse_matrix) % self.field.p

    def from_normal(self, c: np.ndarray) -> np.ndarray:
        """Normal coords -> standard (polynomial) coords."""
        return (c @ self.basis_matrix) % self.field.p

    def frobenius_in_normal_coords(self, c: np.ndarray) -> np.ndarray:
        """The Galois action in normal coordinates: a cyclic shift."""
        return np.roll(c, 1)
